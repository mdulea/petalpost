// Fails when the pages, robots.txt and sitemap.xml disagree on the production origin, the sitemap misses an indexed page or a valid lastmod date, two indexed pages share a title or description, an indexed page has other than one h1, a page links to index.html instead of /, an indexed page other than the home page is linked from fewer than two other indexed pages, a page generated by pnpm pages differs from the committed file, an occasion has no page text or page text names no occasion, a page loads a script, stylesheet, image or frame from another origin, a script writes a cookie, a page has no favicon, the contact address differs between pages, editor.html lacks a control for an invite field, a template's frame or title font has no CSS rule, a CSS custom property refers to itself, the index.html template or accent count differs from the data, the vendored library differs from its published release, a page lacks a skip link to its main element, a page or the Preview button ignores the safe-area insets of notched phones, scripts/server.js answers a path differently from production (including /api and /e/{id}) or does not apply the vercel.json redirects, the buildSite output misses a root page or a file a built page, stylesheet or module loads or links to, or the output contains a package file, server code, a migration, tooling, documentation, a dotfile or a type declaration.
// Run: node scripts/check-site.js
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative, sep } from 'node:path';
import { after, test } from 'node:test';
import { buildSite } from './build.js';
import { startServer } from './server.js';
import { EDITABLE } from '../js/invite.js';
import { ACCENTS, CATEGORIES, TEMPLATES } from '../js/templates.js';
import { OCCASIONS } from './occasions.js';
import { generatePages } from './pages.js';

const read = (file) => readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');
const attr = (html, pattern) => (html.match(pattern) || [])[1];

// Indexed pages are the root pages whose robots tag allows indexing.
const pages = readdirSync(new URL('..', import.meta.url))
  .filter((file) => file.endsWith('.html'))
  .map((file) => ({ file, html: read(file) }))
  .filter(({ html }) => /<meta name="robots" content="index/.test(html));
const canonicals = pages.map(({ html }) => attr(html, /<link rel="canonical" href="([^"]+)"/));
const sitemapLine = attr(read('robots.txt'), /^Sitemap: (\S+)$/m);
const locs = [...read('sitemap.xml').matchAll(/<loc>([^<]+)<\/loc>/g)].map(([, loc]) => loc);

for (const { file, html } of pages) {
  test(`${file} has a canonical URL, Open Graph URL and image, and favicon`, () => {
    const canonical = attr(html, /<link rel="canonical" href="([^"]+)"/);
    const ogUrl = attr(html, /<meta property="og:url" content="([^"]+)"/);
    const ogImage = attr(html, /<meta property="og:image" content="([^"]+)"/);
    assert.ok(canonical && ogUrl && ogImage, 'missing canonical, og:url or og:image');
    assert.equal(new URL(canonical).pathname, file === 'index.html' ? '/' : `/${file}`);
    assert.equal(ogUrl, canonical);
    assert.ok(
      existsSync(new URL(`..${new URL(ogImage).pathname}`, import.meta.url)),
      `og:image ${ogImage} has no file`,
    );
    const icon = attr(html, /<link rel="icon" href="([^"]+)"/);
    assert.ok(
      icon && existsSync(new URL(`../${icon.replace(/^\//, '')}`, import.meta.url)),
      'missing favicon link or file',
    );
  });
}

test('robots.txt names the sitemap', () => assert.ok(sitemapLine));

test('sitemap.xml lists exactly the indexed pages', () => assert.deepEqual([...locs].sort(), [...canonicals].sort()));

// Google trusts lastmod only when it is a real date, so each URL needs one that is not in the future.
test('every sitemap.xml URL has a lastmod date that is not in the future', () => {
  const urls = [...read('sitemap.xml').matchAll(/<url>([\s\S]*?)<\/url>/g)].map(([, url]) => url);
  const invalid = urls.filter((url) => {
    const lastmod = attr(url, /<lastmod>(\d{4}-\d{2}-\d{2})<\/lastmod>/);
    return !lastmod || Number.isNaN(Date.parse(lastmod)) || Date.parse(lastmod) > Date.now();
  });
  assert.deepEqual(invalid, []);
});

test('indexed pages have distinct titles and descriptions and one h1 each', () => {
  const titles = pages.map(({ html }) => attr(html, /<title>([^<]+)<\/title>/));
  const descriptions = pages.map(({ html }) => attr(html, /<meta\s+name="description"\s+content="([^"]+)"/));
  assert.equal(new Set(titles).size, pages.length, `titles: ${titles}`);
  assert.equal(new Set(descriptions.filter(Boolean)).size, pages.length, 'a description is missing or repeated');
  assert.deepEqual(
    pages.filter(({ html }) => (html.match(/<h1\b/g) || []).length !== 1).map(({ file }) => file),
    [],
  );
});

// vercel.json redirects /index.html to /, the canonical home URL, so no page links to the redirect.
test('no page links to index.html', () => {
  const html = readdirSync(new URL('..', import.meta.url)).filter((file) => file.endsWith('.html'));
  assert.deepEqual(
    html.filter((file) => /href="\/?index\.html/.test(read(file))),
    [],
  );
});

// Google finds and ranks a page by the links to it; a page only in the sitemap is an orphan.
test('every indexed page but the home page is linked from at least two other indexed pages', () => {
  const linkedFrom = (target) =>
    pages.filter(({ file, html }) => {
      if (file === target) return false;
      const hrefs = [...html.matchAll(/<a\b[^>]*\bhref="([^"#?]*)/g)].map(([, href]) => href.replace(/^\//, ''));
      return hrefs.includes(target);
    }).length;
  assert.deepEqual(
    pages
      .filter(({ file }) => file !== 'index.html')
      .filter(({ file }) => linkedFrom(file) < 2)
      .map(({ file }) => file),
    [],
  );
});

test('every occasion has page text and all page text names an occasion', () =>
  assert.deepEqual(Object.keys(OCCASIONS).sort(), [...CATEGORIES].sort()));

for (const [file, html] of await generatePages()) {
  test(`${file} matches the output of pnpm pages`, () => assert.equal(read(file), html, 'run pnpm pages'));
}

test('pages, robots.txt and sitemap.xml share one origin', () => {
  const ogImages = pages.map(({ html }) => attr(html, /<meta property="og:image" content="([^"]+)"/));
  const urls = [...canonicals, ...ogImages, sitemapLine, ...locs].filter(Boolean);
  assert.equal(new Set(urls.map((url) => new URL(url).origin)).size, 1);
});

test('every indexed page has the same contact address', () => {
  const addresses = pages.map(({ html }) => attr(html, /href="mailto:([^"]+)"/));
  assert.ok(addresses.every(Boolean), 'a page has no contact address');
  assert.equal(new Set(addresses).size, 1);
});

// The privacy page promises no cookies and nothing loaded from a third party. The only absolute source is
// Vercel's /_vercel/insights/script.js, which has a root-relative address. Adding a tracker that reads or writes on the
// device needs a consent banner first (ePrivacy Art. 5(3)).
test('no page loads a resource from another origin', () => {
  const external = readdirSync(new URL('..', import.meta.url))
    .filter((file) => file.endsWith('.html'))
    .flatMap((file) =>
      [
        ...read(file).matchAll(
          /<(?:script|img|iframe)\b[^>]*\bsrc="(https?:\/\/|\/\/)[^"]*"|<link\b[^>]*\brel="(?:stylesheet|preload|icon)"[^>]*\bhref="(?:https?:\/\/|\/\/)[^"]*"/g,
        ),
      ].map(([tag]) => `${file}: ${tag}`),
    );
  assert.deepEqual(external, []);
});

test('no script writes a cookie', () => {
  const writers = readdirSync(new URL('../js', import.meta.url)).filter(
    (file) => file.endsWith('.js') && /document\.cookie|cookieStore/.test(read(`js/${file}`)),
  );
  assert.deepEqual(writers, []);
});

